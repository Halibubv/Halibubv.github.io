#!/bin/sh
# Запуск приложения в контейнере: веб-сервер на порту $PORT, затем миграции базы и демо-данные.
# set -e: если какой-то шаг упал (например, нет связи с базой), контейнер остановится с ошибкой.
set -e

# Сервер запускаем первым и в фоне (&). Render ждёт, когда приложение откроет порт,
# а создание таблиц в облачной базе может идти дольше, чем он готов ждать.
php -S 0.0.0.0:"$PORT" -t public router.php &
SERVER_PID=$!

echo "Updating database..."
php database/migrate.php

# Демо-данные — только на публичном демо (DEMO_MODE=1).
# RESET_DEMO=1 — пересоздавать их при каждом запуске: брони и заказы снова на «сегодня»,
# а то, что посетители поменяли в демо, сбрасывается. Иначе демо создаётся один раз.
if [ "$DEMO_MODE" = "1" ]; then
    if [ "$RESET_DEMO" = "1" ]; then
        php database/seed-demo.php
    else
        php database/seed-demo.php --if-missing
    fi
fi
echo "Database is ready."

# Дальше просто ждём, пока работает сервер.
wait "$SERVER_PID"
